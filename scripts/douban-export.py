#!/usr/bin/env python3
"""
Douban Collection Export via Frodo API (Mobile App Backend)

Exports book/movie/music/game collections to Markdown, CSV or JSON.
No login, no cookies, no browser required.

Derived from daymade/claude-code-skills (douban-skill), MIT licensed.
The Frodo API approach, HMAC signature scheme and rate-limit values come
from that project. See README.md for full attribution.

The API key and HMAC secret are Douban's mobile app credentials, extracted
from the public APK. They are the same for all users and do not identify you.
No personal credentials are used or stored. Data is fetched only from
frodo.douban.com.

Usage:
    python3 douban-export.py --user <id>
    python3 douban-export.py --format json --type movie,book
    python3 douban-export.py --output-dir ~/notes/media
"""

